import { exec } from 'child_process'
import * as fs from 'fs/promises'
import * as linguistLanguages from 'linguist-languages'
import * as path from 'path'
import { promisify } from 'util'

const execAsync = promisify(exec)

const LANGUAGES_FILE_PATH = path.join(__dirname, '../packages/shared/config/code-languages.ts')

function extractAllCodeExtensions(): string[] {
  console.log('🔍 Extracting language extensions from linguist-languages...')
  const extensionSet = new Set<string>()
  for (const langData of Object.values(linguistLanguages)) {
    const { extensions } = langData as { extensions?: string[] }
    if (Array.isArray(extensions)) {
      for (const ext of extensions) {
        if (typeof ext === 'string' && ext.length > 0) {
          extensionSet.add(ext)
        }
      }
    }
  }
  const sorted = Array.from(extensionSet).sort((a, b) => a.localeCompare(b))
  console.log(`✅ Extracted ${sorted.length} unique code extensions.`)
  return sorted
}

function generateLanguagesFileContent(extensions: string[]): string {
  console.log('📝 Generating code-languages.ts file content...')
  return `/**
 * Flat list of code file extensions extracted from linguist-languages.
 * Generated by \`pnpm update:languages\`. Do not edit manually.
 */
export const codeLangExts: readonly string[] = ${JSON.stringify(extensions)}
`
}

async function format(filePath: string): Promise<void> {
  console.log('🎨 Formatting file with Biome...')
  try {
    await execAsync(`pnpm biome format --write ${filePath}`)
    console.log('✅ Biome formatting complete.')
  } catch (e: any) {
    console.error('❌ Biome formatting failed:', e.stdout || e.stderr)
    throw new Error('Biome formatting failed.')
  }
}

async function checkTypeScript(filePath: string): Promise<void> {
  console.log('🧐 Checking file with TypeScript compiler...')
  try {
    await execAsync(`pnpm tsc --noEmit --skipLibCheck --ignoreConfig ${filePath}`)
    console.log('✅ TypeScript check passed.')
  } catch (e: any) {
    console.error('❌ TypeScript check failed:', e.stdout || e.stderr)
    throw new Error('TypeScript check failed.')
  }
}

async function updateLanguagesFile(): Promise<void> {
  console.log('🚀 Starting to update code-languages.ts...')
  try {
    const extensions = extractAllCodeExtensions()
    const fileContent = generateLanguagesFileContent(extensions)

    await fs.writeFile(LANGUAGES_FILE_PATH, fileContent, 'utf-8')
    console.log(`✅ Successfully wrote to ${LANGUAGES_FILE_PATH}`)

    await format(LANGUAGES_FILE_PATH)
    await checkTypeScript(LANGUAGES_FILE_PATH)

    console.log('🎉 Successfully updated code-languages.ts file!')
    console.log(`📊 Contains ${extensions.length} extensions.`)
  } catch (error) {
    console.error('❌ An error occurred during the update process:', (error as Error).message)
    process.exit(1)
  }
}

if (require.main === module) {
  void updateLanguagesFile()
}

export { updateLanguagesFile }
